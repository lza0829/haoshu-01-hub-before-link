"""枢纽先于链接（架构甲：装载期硬拒绝）

链接入湖前，两端枢纽必须已可解（本批先落或库内已有）；任一条缺端，整批失败闭。

全局唯一架构口径——甲·装载期硬拒绝：
- 装载写闸在落库前预检全批：每条链接两端枢纽、每条卫星父键（含订购卫星的父链接，
  父链若因缺端被拒则级联视为缺端）。缺端清单一次性列全，不短路、不只拒单条。
- 任一缺端 → 整批拒绝：正式枢纽/链接/卫星零写入，回执记「拒绝」，载荷进隔离匣
  （拒绝位·终态）。邻键合法链接同批回滚，但回执是干净的整批失败，非半成功；
  补齐枢纽后同批号可重灌过闸。
- 不设候选区、不做贯验晋升：被拒载荷唯一出路是修正后重灌过闸。
- 贯验只做巡检：证明正式库无缺端残留（链接两端可解 + 拒绝批无正式残留），
  不补做装载闸。禁止「链接已落、贯验再报缺端」。
"""
状态 = "已实现"
架构 = "甲·装载期硬拒绝"

from app.seed import 哈希键

# 链接类 → (链接表, 前缀, 两端枢纽类)
链接口径 = {
    "号卡套餐": ("链接_号卡套餐", "链订购", ("号卡", "套餐")),
    "号卡客户": ("链接_号卡客户", "链实名", ("号卡", "客户")),
}
枢纽表 = {"号卡": "枢纽_号卡", "套餐": "枢纽_套餐", "客户": "枢纽_客户"}
端键名 = {"号卡": "号卡业务键", "套餐": "套餐业务键", "客户": "客户业务键"}


def 链接哈希(链接类: str, 端键: dict[str, str]) -> str:
    """由两端业务键派生链接哈希（枢纽哈希本身即业务键哈希，故缺端也可派生）。"""
    表, 前缀, (甲类, 乙类) = 链接口径[链接类]
    return 哈希键(前缀, 哈希键(甲类, 端键[甲类]), 哈希键(乙类, 端键[乙类]))


def 预检缺端(体: dict, conn) -> dict:
    """装载写闸：落库前对全批做可解性预检（只读，不写库）。

    返回 {"缺端": [...], "涉及链接哈希": [...]}：
    - 缺端：全部缺端明细（链接缺端 + 卫星缺父，含父链缺端级联），空列表=闸过。
    - 涉及链接哈希：本批链接载荷派生的全部链接哈希（无论缺端与否），供回执与巡检。
    """
    枢纽 = 体.get("枢纽") or {}
    链接 = 体.get("链接") or {}
    卫星 = 体.get("卫星") or {}
    缺端 = []

    # 可用枢纽业务键 = 库内已有 ∪ 本批将落（与装载顺序「枢纽先于链接」同口径）
    可用枢纽: dict[str, set[str]] = {}
    for 类, 表 in 枢纽表.items():
        库内 = {r["业务键"] for r in conn.execute(f"SELECT 业务键 FROM {表}")}
        本批 = {
            str(项.get("业务键") or "").strip()
            for 项 in (枢纽.get(类) or [])
            if str(项.get("业务键") or "").strip()
        }
        可用枢纽[类] = 库内 | 本批

    def 端可解(类, 业务键) -> bool:
        return bool(业务键) and 业务键 in 可用枢纽[类]

    # 链接预检：两端枢纽必须都可解；缺端链接不进入「本批合格链接集」
    涉及链接哈希: list[str] = []
    本批合格链接: set[str] = set()
    for 链接类, (表, 前缀, (甲类, 乙类)) in 链接口径.items():
        for 项 in (链接.get(链接类) or []):
            端键 = {
                甲类: str(项.get(端键名[甲类]) or "").strip(),
                乙类: str(项.get(端键名[乙类]) or "").strip(),
            }
            lh = 链接哈希(链接类, 端键)
            涉及链接哈希.append(lh)
            合格 = True
            for 类 in (甲类, 乙类):
                if not 端可解(类, 端键[类]):
                    合格 = False
                    缺端.append({
                        "类": f"链接-{链接类}",
                        "位": f"{类}端",
                        "业务键": 端键[类] or "（空键）",
                        "对端": 端键[乙类 if 类 == 甲类 else 甲类],
                        "链接哈希": lh,
                        "说明": f"{类}枢纽不可解（本批未落且库内无）",
                    })
            if 合格:
                本批合格链接.add(lh)

    # 库内已有链接（订购卫星的合法父）
    库内链接 = {
        r["哈希键"] for r in conn.execute("SELECT 哈希键 FROM 链接_号卡套餐")
    }
    可用订购链 = 库内链接 | 本批合格链接

    # 枢纽卫星预检：父枢纽必须可解
    for 类 in ("号卡", "套餐", "客户"):
        for 项 in (卫星.get(类) or []):
            键 = str(项.get("业务键") or "").strip()
            if not 端可解(类, 键):
                缺端.append({
                    "类": f"卫星-{类}",
                    "位": "父枢纽",
                    "业务键": 键 or "（空键）",
                    "对端": "",
                    "链接哈希": "",
                    "说明": f"{类}枢纽不可解（本批未落且库内无）",
                })

    # 订购卫星预检：父链接必须可解；父链若因缺端被拒则级联缺端
    for 项 in (卫星.get("订购") or []):
        端键 = {
            "号卡": str(项.get("号卡业务键") or "").strip(),
            "套餐": str(项.get("套餐业务键") or "").strip(),
        }
        lh = 链接哈希("号卡套餐", 端键)
        if lh in 可用订购链:
            continue
        级联 = lh in 涉及链接哈希  # 本批试过该链但被缺端刷下 → 级联；否则父链根本不存在
        缺端.append({
            "类": "卫星-订购",
            "位": "父链接",
            "业务键": f"{端键['号卡']}/{端键['套餐']}",
            "对端": "",
            "链接哈希": lh,
            "说明": "父链接本批缺端被拒之级联" if 级联 else "父链接不存在（本批未落且库内无）",
        })

    return {"缺端": 缺端, "涉及链接哈希": 涉及链接哈希}
